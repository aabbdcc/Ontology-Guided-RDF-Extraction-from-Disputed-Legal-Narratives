"""Entry point: python -m src.run_experiment --mode rule_naive|rule_attributed|llm_baseline|llm_guided"""

import argparse
import csv
import json
from pathlib import Path
from rdflib import Graph
from .rdf_utils import ROOT, graph_for, load_jsonl, save_graph
from .extractors import naive_rule, attribution_aware_rule
from .llm_extraction import extract_with_llm
from .validation import validate_graph
from .evaluation import evaluate
from .conflict_detection import detect_conflicts
from .verbalization import verbalize
from rdflib.namespace import RDF
from .rdf_utils import EX

MODES = ("rule_naive", "rule_attributed", "llm_baseline", "llm_guided")


def run(mode, model=None, validation_engine="auto", output=None):
    rows = load_jsonl(ROOT / "data/gold_annotations.jsonl")
    conflicts = json.loads(
        (ROOT / "data/gold_conflicts.json").read_text(encoding="utf-8")
    )
    gold = Graph().parse(ROOT / "data/gold.ttl", format="turtle")
    shapes = Graph().parse(ROOT / "ontology/shapes.ttl", format="turtle")
    ontology = Graph().parse(ROOT / "ontology/ontology.ttl", format="turtle")
    enriched = []
    for row in rows:
        if mode == "rule_naive":
            ann = naive_rule(row["text"])
        elif mode == "rule_attributed":
            ann = attribution_aware_rule(row["text"])
        else:
            if not model:
                raise ValueError("--model is required for LLM modes")
            ann = extract_with_llm(row["text"], model, mode == "llm_guided")
        # Deterministic regex matches cover the complete source string. Their
        # exact quote comes from explicit matching, not a silent RDF fallback.
        if ann is not None and mode.startswith("rule_"):
            ann = {**ann, "source_quote": row["text"]}
        enriched.append({**row, "predicted_annotation": ann})
    pred = graph_for(enriched, annotations_key="predicted_annotation")
    out = Path(output) if output else ROOT / "results" / mode
    out.mkdir(parents=True, exist_ok=True)
    save_graph(pred, out / "predicted.ttl")
    (out / "predictions.jsonl").write_text(
        "".join(
            json.dumps({"id": r["id"], "prediction": r["predicted_annotation"]}) + "\n"
            for r in enriched
        ),
        encoding="utf-8",
    )
    val = validate_graph(pred, shapes, ontology, engine=validation_engine)
    eg = evaluate(gold, pred, rows, conflicts)
    summary = {
        "mode": mode,
        "model": model,
        "data_origin": "fully_synthetic_author_created",
        "method_family": (
            "regex_rules_not_llm" if mode.startswith("rule") else "api_llm"
        ),
        "n_documents": len(rows),
        "evaluation": eg,
        "validation": val,
    }
    (out / "metrics.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    (out / "conflicts.json").write_text(
        json.dumps(detect_conflicts(pred), indent=2), encoding="utf-8"
    )
    return summary


def build_gold():
    rows = load_jsonl(ROOT / "data/gold_annotations.jsonl")
    g = graph_for(rows)
    save_graph(g, ROOT / "data/gold.ttl")
    return g


def save_verbalizations(g):
    selected = ("D01", "D13", "D14", "D19", "D20")
    lines = [
        "# Deterministic RDF → Text template baseline",
        "",
        "NOT generated by an LLM. This is a grounded template-based sanity check.",
        "",
    ]
    for ident in selected:
        node = EX[("payment_" if ident == "D01" else "claim_") + ident]
        lines.append(f"- **{ident}**: {verbalize(g,node)}")
    (ROOT / "results/example_outputs/verbalizations.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=MODES, default="rule_attributed")
    parser.add_argument("--model", help="LLM model ID (only for LLM modes)")
    parser.add_argument(
        "--validation-engine",
        choices=["auto", "pyshacl", "offline_subset"],
        default="auto",
    )
    args = parser.parse_args()
    build_gold()
    report = run(args.mode, args.model, args.validation_engine)
    print(json.dumps({k: v for k, v in report.items() if k != "validation"}, indent=2))
    print(
        f'Validation: {report["validation"]["conforms"]}, engine: {report["validation"]["engine"]}, violations: {report["validation"]["violations"]}'
    )


if __name__ == "__main__":
    main()
